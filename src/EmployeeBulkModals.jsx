/* ---------------------------------------------------------------- Wizard */

function SectionGroup({ title, labels, checked, setChecked }) {
  const all = labels.every(label => checked.includes(label));
  const toggleAll = () => setChecked(previous => (all ? previous.filter(label => !labels.includes(label)) : [...new Set([...previous, ...labels])]));
  const toggle = label => setChecked(previous => (previous.includes(label) ? previous.filter(item => item !== label) : [...previous, label]));
  return <div className="bulk-section-group"><label className="bulk-section-parent"><input type="checkbox" checked={all} onChange={toggleAll} /> {title}</label><div className="bulk-section-children">{labels.map(label => <label key={label}><input type="checkbox" checked={checked.includes(label)} onChange={() => toggle(label)} /> {label}</label>)}</div></div>;
}

