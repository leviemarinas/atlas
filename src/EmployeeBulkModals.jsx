/** Text boxes match part of the value; each checkbox list matches any ticked value; all criteria must hold. */
export function matchesFilter(item, filter) {
  const first = item.firstName || item.name.split(' ')[0]; const last = item.lastName || item.name.split(' ').slice(-1)[0];
  const has = (value, part) => !part.trim() || String(value || '').toLowerCase().includes(part.trim().toLowerCase());
  return has(item.id, filter.employeeCode) && has(first, filter.firstName) && has(last, filter.lastName)
    && (!filter.origins.length || filter.origins.includes(item.origin || 'Philippines'))
    && (!filter.statuses.length || filter.statuses.includes(item.status || 'Full-time'));
}

