/** Checks the Initial_Details sheet. Atlas reports each problem with its Excel line, employee code and message. */
function checkInitialDetails(table, mode, employees) {
  const errors = []; const records = [];
  const at = name => table.headers.findIndex(header => header.toLowerCase() === name.toLowerCase());
  const cols = Object.fromEntries(INITIAL_HEADERS.map(name => [name, at(name)]));
  if (cols['Employee Code'] < 0) return { errors: [{ line: 1, employeeCode: '', message: 'The Employee Code column is missing. Use the downloaded template.' }], records };
  const existing = new Map(employees.map(item => [item.id, item]));
  const seen = new Set();
  const optionMatch = (value, list) => list.find(option => option.toLowerCase() === value.toLowerCase());
  table.rows.forEach((row, index) => {
    const line = index + 2;
    const get = name => (cols[name] >= 0 ? String(row[cols[name]] || '').trim() : '');
    const code = get('Employee Code');
    const problem = message => errors.push({ line, employeeCode: code, message });
    if (!code) { problem('Employee Code is required.'); return; }
    if (seen.has(code)) problem('Employee Code appears more than once in the file.');
    seen.add(code);
    const current = existing.get(code);
    if (mode === 'import' && current) problem('Employee Code already exists. Use Bulk Update to change an existing employee.');
    if (mode === 'update' && !current) problem('Employee Code was not found. Use Bulk Import to add new employees.');
    if (mode === 'import') { if (!get('First Name')) problem('First Name is required.'); if (!get('Last Name')) problem('Last Name is required.'); }
    const status = get('Employment Status'); const origin = get('Origin'); const hire = get('Hire Date');
    const statusValue = status && optionMatch(status, EMPLOYMENT_STATUSES); const originValue = origin && optionMatch(origin, ORIGINS);
    if (status && !statusValue) problem(`Employment Status "${status}" is not in the reference list (${EMPLOYMENT_STATUSES.join(', ')}).`);
    if (origin && !originValue) problem(`Origin "${origin}" is not in the reference list (${ORIGINS.join(', ')}).`);
    let hireIso = '';
    if (hire) {
      const us = /^(\d{1,2})\/(\d{1,2})\/(\d{4})$/.exec(hire); const iso = /^\d{4}-\d{2}-\d{2}$/.test(hire) ? hire : us ? `${us[3]}-${pad(us[1])}-${pad(us[2])}` : '';
      if (!iso || Number.isNaN(Date.parse(iso))) problem(`Hire Date "${hire}" is not a valid date (MM/DD/YYYY).`); else hireIso = iso;
    }
    records.push({ code, firstName: get('First Name'), middleName: get('Middle Name'), lastName: get('Last Name'), status: statusValue || '', origin: originValue || '', hireDate: hireIso });
  });
  return { errors, records };
}

function applyRecords(records, mode, employees) {
  if (mode === 'import') {
    const added = records.map(record => ({ id: record.code, firstName: record.firstName, middleName: record.middleName, lastName: record.lastName, name: [record.firstName, record.middleName, record.lastName].filter(Boolean).join(' '), initials: `${record.firstName[0] || ''}${record.lastName[0] || ''}`.toUpperCase(), status: record.status || 'Full-time', origin: record.origin || 'Philippines', hireDate: record.hireDate, role: '', location: 'PBS | Makati' }));
    return [...added, ...employees];
  }
  const byCode = new Map(records.map(record => [record.code, record]));
  // A blank cell keeps the value the employee already has.
  return employees.map(item => {
    const record = byCode.get(item.id); if (!record) return item;
    const firstName = record.firstName || item.firstName || item.name.split(' ')[0]; const lastName = record.lastName || item.lastName || item.name.split(' ').slice(-1)[0]; const middleName = record.middleName || item.middleName || '';
    return { ...item, firstName, middleName, lastName, name: [firstName, middleName, lastName].filter(Boolean).join(' '), initials: `${firstName[0] || ''}${lastName[0] || ''}`.toUpperCase(), status: record.status || item.status, origin: record.origin || item.origin, hireDate: record.hireDate || item.hireDate };
  });
}

/* --------------------------------------------------------------- History */

export function readBulkHistory() {
  try { const saved = JSON.parse(localStorage.getItem(HISTORY_KEY)); return Array.isArray(saved) ? saved : []; } catch { return []; }
}
function addBulkHistory(entry) {
  try { localStorage.setItem(HISTORY_KEY, JSON.stringify([entry, ...readBulkHistory()].slice(0, 50))); } catch { /* history is a convenience */ }
}

