export function FilterModal({ applied, onApply, onClose }) {
  const [draft, setDraft] = useState(applied);
  const toggle = (key, value) => setDraft(previous => ({ ...previous, [key]: previous[key].includes(value) ? previous[key].filter(item => item !== value) : [...previous[key], value] }));
  const text = (key, label, placeholder) => <details open className="filter-item"><summary>{label}</summary><input value={draft[key]} placeholder={placeholder} onChange={event => setDraft({ ...draft, [key]: event.target.value })} /></details>;
  const list = (key, label, options) => <details open className="filter-item"><summary>{label}</summary><div className="filter-checks">{options.map(option => <label key={option}><input type="checkbox" checked={draft[key].includes(option)} onChange={() => toggle(key, option)} /> {option}</label>)}</div></details>;
  return <div className="modal-backdrop"><section className="modal employee-filter-modal" role="dialog" aria-modal="true" aria-label="Filter Table"><header><h2>Filter Table</h2><button className="icon-button" onClick={onClose} aria-label="Close"><X /></button></header><div className="modal-body">
    <p className="form-text">Choose criteria to filter the table:</p>
    {text('employeeCode', 'Employee Code', 'Input Employee Code')}{text('firstName', 'First Name', 'Input First Name')}{text('lastName', 'Last Name', 'Input Last Name')}
    {list('origins', 'Origin', ORIGINS)}{list('statuses', 'Employment Status', EMPLOYMENT_STATUSES)}
    <div className="modal-actions"><button className="button secondary" onClick={() => setDraft(EMPTY_FILTER)}>Reset</button><button className="button primary" onClick={() => onApply(draft)}>Apply Filter</button></div>
  </div></section></div>;
}

