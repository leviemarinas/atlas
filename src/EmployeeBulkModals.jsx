/** Atlas exports every employee (the search box and filter are not applied) with these properties. */
const EXPORT_HEADERS = ['EmployeeCode', 'FirstName', 'MiddleName', 'LastName', 'FullName', 'Origin', 'EmploymentStatus', 'HireDate'];
const csvCell = value => (value === undefined || value === null || value === '' ? '""' : `"${String(value).replaceAll('"', '""')}"`);

/** Writes the table in Atlas's export layout: a four-line banner, then the header row and the data. */
function exportTable(moduleName, headers, rows, format) {
  const now = new Date();
  const title = `${moduleName} Exported Data`;
  const banner = ['Atlas', title, `Created on: ${stamp(now)}`, `Generated by: ${ACTOR}`];
  const file = `${moduleName}-export_data_${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}`;
  if (format === 'csv') {
    const text = [...banner, '', headers.map(csvCell).join(','), ...rows.map(row => row.map(csvCell).join(','))].join('\r\n');
    downloadFile(`${file}.csv`, text, 'text/csv;charset=utf-8');
  } else if (format === 'xlsx') {
    downloadFile(`${file}.xlsx`, makeXlsx('Sheet1', [banner[0]], [[banner[1]], [banner[2]], [banner[3]], [], headers, ...rows]), XLSX_MIME);
  } else if (format === 'pdf') {
    downloadFile(`${file}.pdf`, makePdf(`Atlas - ${title}`, headers, rows), 'application/pdf');
  } else {
    downloadFile(`${file}.docx`, makeDocx(`Atlas - ${title}`, headers, rows), DOCX_MIME);
  }
}

export function exportEmployees(employees, format) {
  const rows = employees.map(item => {
    const first = item.firstName || item.name.split(' ')[0];
    const last = item.lastName || item.name.split(' ').slice(-1)[0];
    return [item.id, first, item.middleName || '', last, `${first} ${last}`, item.origin || 'Philippines', item.status || 'Full-time', usDate(item.hireDate)];
  });
  exportTable('Company Employee', EXPORT_HEADERS, rows, format);
}

